// City order for the index page (mirrors GPL's regional grouping).
export const cityOrder: string[] = [
  'Mumbai',
  'Mumbai (Panvel)',
  'Pune',
  'Bengaluru',
  'Hyderabad',
  'Chennai',
  'Gurugram',
  'Delhi',
  'Noida',
  'Panipat',
  'Kolkata',
];

export function getProjectBySlug(slug: string): Project | undefined {
  return projects.find((p) => p.slug === slug);
}

export function getAllSlugs(): string[] {
  return projects.map((p) => p.slug);
}

export function groupByCity(): Record<string, Project[]> {
  const grouped: Record<string, Project[]> = {};
  for (const city of cityOrder) grouped[city] = [];
  for (const p of projects) {
    if (!grouped[p.city]) grouped[p.city] = [];
    grouped[p.city].push(p);
  }
  // Drop empty cities
  for (const c of Object.keys(grouped)) if (grouped[c].length === 0) delete grouped[c];
  return grouped;
}
